/** Reverse map: QMK basic keycode name -> KeyboardEvent.code. */
export const keycodeToDomCode: Record<string, string> = Object.fromEntries(
  Object.entries(domCodeToKeycode)
    .filter(([code]) => !code.startsWith('OS') && !code.startsWith('Volume'))
    .map(([code, kc]) => [kc, code]),
);
